const assert = require('node:assert/strict');
const { test } = require('node:test');
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { createHash } = require('node:crypto');
const { start, actor } = require('./helpers/staging.cjs');

const a = 'atelier-temoin', b = 'atelier-controle';
const headers = { 'X-Feedback-Channel': 'a'.repeat(32) };
const notes = project => `/api/client-feedback?project=${project}`;
const decisions = project => `/api/client-decisions?project=${project}`;
const render = project => `/projects/${project}/generated/renders/facade.jpg`;
const pose = { p: [0, 8, 0.01], q: [0, 0, 0, 1], f: 42, e: 1 };
const variant = { v: 1, project: a, name: 'Bois du témoin', floor: 'oak', facade: 'timber', hour: 13, pose };

const openssl = spawnSync('openssl', ['version']).status === 0;
test('Recette HTTPS : rôles, avis, validation immuable et rendu refusé après révocation', { skip: openssl ? false : 'OpenSSL absent' }, async t => {
  const stage = await start();
  t.after(stage.stop);
  const guest = actor(stage), architect = actor(stage), reader = actor(stage), commenter = actor(stage);
  assert.equal((await guest.request(render(a))).status, 401);
  const login = await architect.api('login', { password: stage.password });
  assert.equal(login.status, 200);
  assert.match(login.headers['set-cookie'][0], /^__Host-plan3d=.*HttpOnly; SameSite=Lax;.*Secure/);
  const entry = await architect.request('/');
  assert.equal(entry.status, 302);
  assert.equal(entry.headers.location, `/index.html?project=${a}`);
  assert.deepEqual((await architect.request('/api/projects')).json().map(p => p.slug).sort(), [a, b].sort());
  const openInvite = async (client, role) => {
    const created = await architect.api('invitations', { project: a, role, validHours: 1 });
    assert.equal(created.status, 201);
    const { token, invitation } = created.json();
    assert.equal((await client.api('accept', { token })).status, 200);
    return invitation;
  };
  await openInvite(reader, 'read');
  const invitation = await openInvite(commenter, 'comment');
  assert.equal((await reader.request(`/index.html?project=${a}`)).status, 200);
  assert.equal((await reader.request('/js/clientDecisions.js')).status, 200);
  const warm = await commenter.request(render(a));
  assert.equal(warm.status, 200);
  assert.equal(warm.headers['cache-control'], 'private, no-store');
  assert.match(warm.headers['strict-transport-security'], /^max-age=/);
  assert.equal((await commenter.request(render(a), { headers: { Range: 'bytes=0-99' } })).status, 206);
  assert.equal((await commenter.request(render(b))).status, 403);
  const draft = { text: 'Le bois est-il prévu ?', point: [0, 0, 0], pose };
  for (const origin of [undefined, 'https://ailleurs.test']) {
    assert.equal((await commenter.request(notes(a), { headers: { ...headers, Origin: origin }, body: draft })).status, 403);
  }
  assert.equal((await reader.request(notes(a), { headers, body: draft })).status, 403);
  const published = await commenter.request(notes(a), { headers, body: draft });
  assert.equal(published.status, 201);
  const note = published.json().item;
  const review = { headers, method: 'PATCH', body: { id: note.id, revision: 0, status: 'answered', reply: 'Oui, pour cette version.' } };
  assert.equal((await commenter.request(notes(a), review)).status, 403);
  assert.equal((await architect.request(notes(a), review)).status, 200);
  assert.equal((await architect.request(notes(a), review)).status, 409);
  assert.equal((await reader.request(notes(a), { headers })).json().notes[0].status, 'answered');
  const complete = { ...review, body: { ...review.body, revision: 1, status: 'closed' } };
  assert.equal((await architect.request(notes(a), complete)).json().item.status, 'closed');
  const model = path.join(stage.root, 'projects', a, 'project.json');
  const modelHash = createHash('sha256').update(fs.readFileSync(model)).digest('hex');
  const publishing = { headers, body: { action: 'propose', variant, modelHash } };
  assert.equal((await architect.request(decisions(a), { headers, body: { action: 'propose', variant } })).status, 409);
  assert.equal((await commenter.request(decisions(a), publishing)).status, 403);
  const proposal = (await architect.request(decisions(a), publishing)).json().item;
  const approve = { headers, body: { action: 'approve', id: proposal.id, modelHash, variant: { ...variant, floor: 'concrete' } } };
  assert.equal((await reader.request(decisions(a), approve)).status, 403);
  assert.equal((await architect.request(decisions(a), approve)).status, 403);
  assert.equal((await commenter.request(decisions(a), { headers, body: { action: 'approve', id: proposal.id, modelHash: 'f'.repeat(64) } })).status, 409);
  const approved = (await commenter.request(decisions(a), approve)).json().item;
  assert.equal(approved.approval.snapshot.floor, 'oak', 'l’instantané vient du serveur, pas du formulaire client');
  assert.ok(Number.isFinite(Date.parse(approved.approval.approvedAt)));
  assert.deepEqual((await commenter.request(decisions(a), approve)).json().item.approval, approved.approval);
  const newer = (await architect.request(decisions(a), { ...publishing, body: { ...publishing.body, variant: { ...variant, floor: 'tile' } } })).json().item;
  assert.equal(newer.approval, null);
  const otherFolder = { headers: { 'X-Feedback-Channel': 'b'.repeat(32) } };
  assert.deepEqual((await reader.request(decisions(a), otherFolder)).json().proposals, []);
  assert.equal((await commenter.request(decisions(a), { ...approve, ...otherFolder })).status, 404);
  assert.equal((await reader.request(decisions(b), { headers })).status, 403);
  fs.appendFileSync(model, '\n');
  const records = (await reader.request(decisions(a), { headers })).json().proposals;
  assert.deepEqual(records[0].approval, approved.approval);
  assert(records.every(record => record.modelChanged));
  assert.equal((await commenter.request(decisions(a), { ...approve, body: { action: 'approve', id: newer.id, modelHash } })).status, 409);
  assert.equal((await architect.api('revoke', { id: invitation.id })).status, 200);
  const denied = await commenter.request(render(a), { headers: { Range: 'bytes=0-99', 'If-None-Match': '"previous"' } });
  assert.equal(denied.status, 401);
  assert.equal(denied.headers['cache-control'], 'private, no-store');
  assert.equal((await commenter.request(decisions(a), { headers })).status, 401);
  assert.equal((await reader.request(render(a))).status, 200, 'une autre invitation reste inchangée');
});

test('Enregistrement projet : erreurs JSON utilisables et validation avant écriture', { skip: openssl ? false : 'OpenSSL absent' }, async t => {
  const stage = await start();
  t.after(stage.stop);
  const architect = actor(stage);
  const route = '/api/save-project';
  assert.equal((await architect.api('login', { password: stage.password })).status, 200);
  const slug = 'test-edition';
  const target = path.join(stage.root, 'projects', slug, 'project.json');
  const project = { meta: { name: 'Test édition' }, config: {}, walls: [{ from: [0, 0], to: [2, 0] }], rooms: [] };
  const rejected = await architect.request(route, { body: { slug, project: { ...project, walls: [] } } });
  assert.equal(rejected.status, 422);
  assert.match(rejected.json().error, /mur/);
  assert.equal(fs.existsSync(path.dirname(target)), false);
  const cameraError = await architect.request(route, { body: { slug, project: { ...project, tourWaypoints: [] } } });
  assert.equal(cameraError.status, 422);
  assert.match(cameraError.json().error, /caméra/);
  const tooBig = await architect.request(notes(a), { headers, body: { text: 'x'.repeat(9000) } });
  assert.equal(tooBig.status, 413);
  assert.match(tooBig.json().error, /taille/);
  const unsupported = await architect.request(route, { method: 'POST', headers: { Origin: stage.origin, 'Content-Type': 'text/plain' } });
  assert.equal(unsupported.status, 415);
  const saved = await architect.request(route, { body: { slug, project } });
  assert.equal(saved.status, 200);
  assert.equal(saved.json().ok, true);
  assert.deepEqual(JSON.parse(fs.readFileSync(target)), project);
  const invalidImage = await architect.request(route, { body: { slug, project: { ...project, meta: { name: 'Jamais écrit' } }, planImage: 'data:image/png;base64,QUJD' } });
  assert.equal(invalidImage.status, 422);
  assert.deepEqual(JSON.parse(fs.readFileSync(target)), project);
  assert(!fs.readdirSync(path.dirname(target)).some(file => file.endsWith('.tmp')));
  const jpg = fs.readFileSync(path.join(stage.root, 'projects', a, 'generated/renders/facade.jpg'));
  const withImage = await architect.request(route, { body: { slug, project, planImage: `data:image/jpeg;base64,${jpg.toString('base64')}` } });
  assert.equal(withImage.status, 200);
  assert.equal(withImage.json().planImage.url, `projects/${slug}/plan.jpg`);
  assert.deepEqual(fs.readFileSync(path.join(path.dirname(target), 'plan.jpg')), jpg);
  const raw = await architect.request(route, { method: 'POST', headers: { Origin: stage.origin, 'Content-Type': 'application/json' } });
  assert.equal(raw.status, 400);
  assert.match(raw.json().error, /JSON/);
});
